import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const schema = JSON.parse(readFileSync(resolve(root, 'packages/contracts/schema/v1.json'), 'utf8'));
const graph = JSON.parse(readFileSync(resolve(root, 'packages/contracts/schema/action-transitions.v1.json'), 'utf8'));
const defs = schema.$defs;
const names = Object.keys(defs);
const allowed = new Set(['type', '$ref', 'const', 'enum', 'properties', 'required', 'additionalProperties', 'items', 'minItems', 'maxItems', 'uniqueItems', 'minLength', 'maxLength', 'pattern', 'format', 'minimum', 'maximum', 'allOf', 'anyOf', 'oneOf', 'not', 'if', 'then', 'else', 'description']);

// This intentionally small generator handles only the checked-in vocabulary.
// Validation constraints stay in JSON Schema; types are never authority/proof.
export function lint(node, path = '#') {
  for (const key of Object.keys(node)) {
    if (!allowed.has(key)) throw new Error(`Unsupported schema keyword ${path}/${key}`);
  }
  if (node.$ref && (!node.$ref.startsWith('#/$defs/') || !(node.$ref.slice(8) in defs))) {
    throw new Error(`Unresolved or external reference at ${path}`);
  }
  if (node.properties) {
    for (const [key, child] of Object.entries(node.properties)) lint(child, `${path}/properties/${key}`);
  }
  for (const key of ['items', 'not', 'if', 'then', 'else']) if (node[key]) lint(node[key], `${path}/${key}`);
  for (const key of ['allOf', 'anyOf', 'oneOf']) for (const child of node[key] ?? []) lint(child, `${path}/${key}`);
}

const pascal = (s) => s.toLowerCase().split('_').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
function typeOf(node, lang) {
  if (node.$ref) return node.$ref.slice(8);
  if (lang === 'ts' && node.const !== undefined) return JSON.stringify(node.const);
  if (lang === 'ts' && node.enum) return node.enum.map(JSON.stringify).join(' | ');
  switch (node.type) {
    case 'string': return lang === 'ts' ? 'string' : 'String';
    case 'integer': return lang === 'ts' ? 'number' : 'crate::SafeInteger';
    case 'number': return lang === 'ts' ? 'number' : 'f64';
    case 'boolean': return lang === 'ts' ? 'boolean' : 'bool';
    case 'array': return lang === 'ts' ? `Array<${typeOf(node.items, lang)}>` : `Vec<${typeOf(node.items, lang)}>`;
    default: throw new Error(`Unsupported structural type ${node.type}; introduce a named definition`);
  }
}

export function generate() {
  for (const [name, node] of Object.entries(defs)) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Bad type name ${name}`);
    lint(node, `#/$defs/${name}`);
    if (node.type === 'object') {
      if (node.additionalProperties !== false) throw new Error(`${name} must reject unknown fields`);
      for (const key of Object.keys(node.properties)) if (!/^[a-z][a-z0-9_]*$/.test(key)) throw new Error(`Bad field ${key}`);
      for (const key of node.required ?? []) if (!(key in node.properties)) throw new Error(`Unknown required field ${name}.${key}`);
    }
  }
  const states = defs.ActionState.enum;
  if (JSON.stringify(Object.keys(graph)) !== JSON.stringify(states)) throw new Error('Action graph and enum differ');
  for (const [from, targets] of Object.entries(graph)) {
    if (new Set(targets).size !== targets.length || targets.some((to) => !states.includes(to) || from === to)) throw new Error(`Invalid graph row ${from}`);
  }
  let ts = '// Generated by scripts/generate-contracts.mjs. DO NOT EDIT.\n// Runtime validation is required; types do not encode all schema constraints.\n\n';
  let rs = '// Generated by scripts/generate-contracts.mjs. DO NOT EDIT.\n// Runtime validation is required; types do not encode all schema constraints.\n\n';
  for (const [name, node] of Object.entries(defs)) {
    if (node.type === 'object') {
      ts += `export interface ${name} {\n`;
      rs += `#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n`;
      for (const [key, child] of Object.entries(node.properties)) {
        const optional = !node.required.includes(key);
        ts += `  ${key}${optional ? '?' : ''}: ${typeOf(child, 'ts')};\n`;
        if (optional) rs += '    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
        rs += `    pub ${key}: ${optional ? `Option<${typeOf(child, 'rs')}>` : typeOf(child, 'rs')},\n`;
      }
      ts += '}\n\n'; rs += '}\n\n';
    } else {
      ts += `export type ${name} = ${typeOf(node, 'ts')};\n\n`;
      if (node.enum) {
        const variants = node.enum.map(pascal);
        if (new Set(variants).size !== variants.length) throw new Error(`Enum collision in ${name}`);
        rs += `#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\npub enum ${name} {\n`;
        node.enum.forEach((value, i) => { rs += `    #[serde(rename = ${JSON.stringify(value)})]\n    ${variants[i]},\n`; });
        rs += '}\n\n';
      } else rs += `pub type ${name} = ${typeOf(node, 'rs')};\n\n`;
    }
  }
  const contracts = names.filter((name) => defs[name].type === 'object');
  ts += 'export interface ContractMap {\n' + contracts.map((name) => `  ${name}: ${name};`).join('\n') + '\n}\n';
  rs += 'pub const CONTRACT_NAMES: &[&str] = &[\n' + contracts.map((name) => `    "${name}",`).join('\n') + '\n];\n\n';
  for (const name of contracts) {
    rs += `impl crate::sealed::Sealed for ${name} {}\nimpl crate::Contract for ${name} { const NAME: &'static str = "${name}"; }\n`;
  }
  rs += '\n/// Graph membership only; not permission, replay safety, or dispatch admission.\npub fn is_action_transition_allowed(from: ActionState, to: ActionState) -> bool {\n    match from {\n';
  for (const [from, targets] of Object.entries(graph)) {
    const result = targets.length ? `matches!(to, ${targets.map((to) => `ActionState::${pascal(to)}`).join(' | ')})` : 'false';
    rs += `        ActionState::${pascal(from)} => ${result},\n`;
  }
  rs += '    }\n}\n';
  const graphJs = '// Generated. Graph membership is NOT authority or safe replay.\n' +
    `export const actionTransitions = ${JSON.stringify(graph, null, 2)};\n` +
    'export function isActionTransitionAllowed(from, to) {\n  return Object.hasOwn(actionTransitions, from) && actionTransitions[from].includes(to);\n}\n';
  return new Map([
    ['packages/contracts/src/generated/types.ts', ts],
    ['packages/contracts/src/generated/action-transitions.mjs', graphJs],
    ['crates/contracts/src/generated.rs', rs],
  ]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/generate-contracts.mjs [--check]');
  for (const [path, content] of generate()) {
    const target = resolve(root, path);
    if (process.argv.includes('--check')) {
      if (readFileSync(target, 'utf8') !== content) throw new Error(`Generated drift: ${path}`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  console.log(process.argv.includes('--check') ? 'Generated contracts match source.' : 'Generated Rust and TypeScript contracts.');
}
