import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = JSON.parse(readFileSync(resolve(root, 'packages/contracts/schema/worker.v1.json'), 'utf8'));
const vocabulary = new Set(['type', '$ref', 'const', 'enum', 'properties', 'required', 'additionalProperties', 'items', 'minItems', 'maxItems', 'uniqueItems', 'minLength', 'maxLength', 'pattern', 'minimum', 'maximum', 'allOf', 'not', 'if', 'then', 'else']);
const pascal = (s) => s.toLowerCase().split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

export function generateWorker(schema = source) {
  const defs = schema.$defs;
  function lint(node) {
    for (const k of Object.keys(node)) if (!vocabulary.has(k)) throw new Error('Unsupported worker schema keyword');
    if (node.$ref && (!node.$ref.startsWith('#/$defs/') || !Object.hasOwn(defs, node.$ref.slice(8)))) throw new Error('Nonlocal worker reference');
    for (const child of Object.values(node.properties ?? {})) lint(child);
    for (const k of ['items', 'not', 'if', 'then', 'else']) if (node[k]) lint(node[k]);
    for (const child of node.allOf ?? []) lint(child);
  }
  function type(node, rust) {
    if (node.$ref) return node.$ref.slice(8);
    if (!rust && node.const !== undefined) return JSON.stringify(node.const);
    if (!rust && node.enum) return node.enum.map(JSON.stringify).join(' | ');
    if (node.type === 'array') return rust ? `Vec<${type(node.items, true)}>` : `Array<${type(node.items, false)}>`;
    const primitive = rust ? { string: 'String', integer: 'crate::SafeInteger', boolean: 'bool' } : { string: 'string', integer: 'number', boolean: 'boolean' };
    if (!primitive[node.type]) throw new Error('Unsupported worker structural type');
    return primitive[node.type];
  }
  let ts = '// Generated by scripts/generate-worker-contracts.mjs. DO NOT EDIT.\n// Value validation is not channel authentication or current authority.\n\n';
  let rs = ts;
  const objects = [];
  for (const [name, node] of Object.entries(defs)) {
    if (!/^Worker[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error('Invalid worker type name');
    lint(node);
    if (node.type === 'object') {
      if (node.additionalProperties !== false || !Array.isArray(node.required)) throw new Error('Worker objects must be closed');
      for (const k of node.required) if (!Object.hasOwn(node.properties, k)) throw new Error('Unknown required field');
      objects.push(name);
      ts += `export interface ${name} {\n`;
      rs += `#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n`;
      for (const [k, field] of Object.entries(node.properties)) {
        if (!/^[a-z][a-z0-9_]*$/.test(k) || ['self', 'super', 'crate', 'type', 'ref', 'mod', 'match', 'async', 'await', 'move', 'loop', 'use', 'fn', 'pub', 'struct', 'enum'].includes(k)) throw new Error('Unsupported worker field name');
        const optional = !node.required.includes(k);
        ts += `  ${k}${optional ? '?' : ''}: ${type(field, false)};\n`;
        if (optional) rs += '    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
        rs += `    pub ${k}: ${optional ? `Option<${type(field, true)}>` : type(field, true)},\n`;
      }
      ts += '}\n\n'; rs += '}\n\n';
    } else {
      ts += `export type ${name} = ${type(node, false)};\n\n`;
      if (node.enum) {
        const variants = node.enum.map(pascal);
        if (new Set(variants).size !== variants.length || variants.includes('Self')) throw new Error('Worker enum collision');
        rs += `#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\npub enum ${name} {\n`;
        node.enum.forEach((v, i) => { rs += `    #[serde(rename = ${JSON.stringify(v)})]\n    ${variants[i]},\n`; });
        rs += '}\n\n';
      } else rs += `pub type ${name} = ${type(node, true)};\n\n`;
    }
  }
  ts += 'export interface WorkerContractMap {\n' + objects.map((n) => `  ${n}: ${n};`).join('\n') + '\n}\n';
  rs += 'pub const CONTRACT_NAMES: &[&str] = &[\n' + objects.map((n) => `    "${n}",`).join('\n') + '\n];\n\n';
  for (const n of objects) rs += `impl crate::sealed::Sealed for ${n} {}\nimpl crate::Contract for ${n} { const NAME: &'static str = "${n}"; }\n`;
  return new Map([['packages/contracts/src/generated/worker.ts', ts], ['crates/contracts/src/worker.rs', rs]]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((a) => a !== '--check')) throw new Error('Usage: generate-worker-contracts.mjs [--check]');
  for (const [name, body] of generateWorker()) {
    const path = resolve(root, name);
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== body) throw new Error(`Generated worker drift: ${name}`);
    } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, body); }
  }
  console.log(process.argv.includes('--check') ? 'Worker contracts match source.' : 'Generated worker contracts.');
}
