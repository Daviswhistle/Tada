// Model events have their own version; existing task/control/worker contracts stay unchanged.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = JSON.parse(readFileSync(resolve(root, 'packages/contracts/schema/model.v1.json'), 'utf8'));
const vocabulary = new Set(['type','$ref','const','enum','oneOf','properties','required','additionalProperties','minLength','maxLength','pattern','minimum','maximum']);

export function generateModel(schema = source) {
  const defs = schema.$defs;
  if (!defs || schema.$schema !== 'https://json-schema.org/draft/2020-12/schema') throw new Error('MODEL_SCHEMA_ROOT');
  function lint(node) {
    for (const key of Object.keys(node)) if (!vocabulary.has(key)) throw new Error('MODEL_SCHEMA_KEYWORD');
    if (node.$ref && (!node.$ref.startsWith('#/$defs/') || !Object.hasOwn(defs, node.$ref.slice(8)) || Object.keys(node).length !== 1)) throw new Error('MODEL_SCHEMA_REFERENCE');
    if (node.oneOf && (Object.keys(node).length !== 1 || node.oneOf.length < 2 || node.oneOf.some((v) => !v.$ref))) throw new Error('MODEL_SCHEMA_UNION');
    for (const child of Object.values(node.properties ?? {})) lint(child);
    for (const child of node.oneOf ?? []) lint(child);
  }
  function type(node, rust) {
    if (node.$ref) return node.$ref.slice(8);
    if (node.oneOf) return node.oneOf.map((v) => type(v, rust)).join(' | ');
    if (!rust && node.const !== undefined) return JSON.stringify(node.const);
    if (!rust && node.enum) return node.enum.map((v) => JSON.stringify(v)).join(' | ');
    const result = (rust ? {string:'String',integer:'crate::SafeInteger'} : {string:'string',integer:'number'})[node.type];
    if (!result) throw new Error('MODEL_SCHEMA_TYPE');
    return result;
  }
  const header = '// Generated by scripts/generate-model-contracts.mjs. DO NOT EDIT.\n// Stream completion is not tool authority or task completion.\n\n';
  let ts = header, rs = header;
  const contracts = [];
  for (const [name, node] of Object.entries(defs)) {
    if (!/^Model[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error('MODEL_SCHEMA_NAME');
    lint(node);
    if (node.oneOf) {
      contracts.push(name);
      ts += `export type ${name} = ${type(node, false)};\n\n`;
      rs += '#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(untagged)]\n';
      rs += `pub enum ${name} {\n` + node.oneOf.map((v) => `    ${v.$ref.slice(13)}(${v.$ref.slice(8)}),`).join('\n') + '\n}\n\n';
    } else if (node.type === 'object') {
      if (node.additionalProperties !== false || !Array.isArray(node.required)
          || new Set(node.required).size !== node.required.length
          || node.required.length !== Object.keys(node.properties).length
          || node.required.some((key) => !Object.hasOwn(node.properties, key))) throw new Error('MODEL_SCHEMA_OBJECT');
      contracts.push(name);
      ts += `export interface ${name} {\n`;
      rs += '#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\n';
      rs += `pub struct ${name} {\n`;
      for (const [key, field] of Object.entries(node.properties)) {
        if (!/^[a-z][a-z0-9_]*$/.test(key) || ['self','super','crate','ref','mod','match','async','await','move','loop','use','fn','pub','struct','enum'].includes(key)) throw new Error('MODEL_SCHEMA_FIELD');
        ts += `  ${key}: ${type(field, false)};\n`;
        rs += `    pub ${key === 'type' ? 'r#type' : key}: ${type(field, true)},\n`;
      }
      ts += '}\n\n'; rs += '}\n\n';
    } else {
      ts += `export type ${name} = ${type(node, false)};\n\n`;
      rs += `pub type ${name} = ${type(node, true)};\n\n`;
    }
  }
  ts += 'export interface ModelContractMap {\n' + contracts.map((name) => `  ${name}: ${name};`).join('\n') + '\n}\n';
  rs += 'pub const CONTRACT_NAMES: &[&str] = &[\n' + contracts.map((name) => `    "${name}",`).join('\n') + '\n];\n\n';
  for (const name of contracts) rs += `impl crate::sealed::Sealed for ${name} {}\nimpl crate::Contract for ${name} { const NAME: &'static str = "${name}"; }\n`;
  return new Map([['packages/contracts/src/generated/model.ts',ts],['crates/contracts/src/model.rs',rs]]);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((v) => v !== '--check')) throw new Error('MODEL_GENERATOR_ARGUMENT');
  for (const [name, content] of generateModel()) {
    const path = resolve(root,name);
    if (process.argv.includes('--check')) {
      if (readFileSync(path,'utf8') !== content) throw new Error('MODEL_GENERATED_DRIFT');
    } else { mkdirSync(dirname(path),{recursive:true}); writeFileSync(path,content); }
  }
  console.log('Model contracts match source.');
}
